function stoptrial(mh,success)
mh.setstate('stop_autogenerated')

% Blank the display through the in-trial path first: for an empty command
% list the renderer flips a cleared stimulus window, so the task's last frame
% is gone before we leave the trial. Then publish a final frame with
% trialStarted=0 so the renderer actually LEAVES the trial. Previously
% trialstarted=0 was set only after the last publish, so on a force-stop the
% newest frame still said trialStarted=1 and the renderer stayed in-trial:
% no isGraphicsReady (graphics lamp red), and the idle loop stalling on it.
for i=1:50
    mh.Screen('clearbuffer');
    mh.Screen('sendtogr')
    pause(0.001)
end
mh.trialstarted = 0;
mh.runtrial = 0;
mh.Screen('clearbuffer');
mh.Screen('sendtogr');            % trialStarted=0 reaches the renderer

flush(mh.graphicsport);
mh.graphicssent=1;
mh.trial.success=success;
if success
    mh.sum_success=mh.sum_success+1;
end
end
