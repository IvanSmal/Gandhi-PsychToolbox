function ev = stimulusRequests(mh)
%STIMULUSREQUESTS This trial's change log, as the start of data.stimulus_events.
%   One row per item appearing or disappearing on the display and per state
%   change, with the ID (request_frame) and Psychtoolbox time (request_secs)
%   of the first frame that asked for it, as publishFrame logged them.
%   trialRecord turns request_secs into requested_ms when the trial is saved;
%   GraphicsHandler fills in the display columns when it saves its flip log
%   (buildStimulusTiming) and drops request_frame. Until then they are NaN.
%   documentation/timing.md describes every column.
n = mh.stimReqN;
z = nan(n, 1);
ev = struct( ...
    'tag',             {col(mh.stimReqTag(1:n))}, ...
    'kind',            {col(mh.stimReqKind(1:n))}, ...
    'event',           {col(mh.stimReqEvent(1:n))}, ...
    'state',           {col(mh.stimReqState(1:n))}, ...
    'entry',           z, ...
    'requested_ms',    z, ...
    'displayed_ms',    z, ...
    'photon_ms',       z, ...
    'delay_ms',        z, ...
    'displayed_tick',  z, ...
    'photon_tick',     z, ...
    'flip',            z, ...
    'frame_id',        z, ...
    'x_deg',           z, ...
    'y_deg',           z, ...
    'rect_px',         nan(n, 4), ...
    'missed',          false(n, 1), ...
    'request_frame',   col(mh.stimReqSeq(1:n)), ...
    'request_secs',    col(mh.stimReqTime(1:n)));
end

function v = col(v)
v = reshape(v, [], 1);
end
