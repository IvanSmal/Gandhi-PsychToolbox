function s = trialRecord(tr, screenparams)
%TRIALRECORD The saved form of a trial: every time on the trial's own timeline.
%   S = trialRecord(TR, SCREENPARAMS) turns the trial MHost2 ran (a trial
%   object) into the struct saved in the trial file and later in e.trial.
%   MHost2's savestate calls it at the end of each trial; GraphicsHandler
%   then adds what the display showed (buildStimulusTiming). A trial already
%   in this form is returned unchanged. SCREENPARAMS ([] = this rig's
%   config) converts target positions to degrees.
%
%   The timeline: every *_ms value is milliseconds since the trial start -
%   when setstate('start_autogenerated') ran - measured on the NIP (Trellis)
%   clock, so any two can be subtracted. trial.start_tick is that moment as
%   a NIP tick: tick = start_tick + 30*ms. During the trial MHost2 keeps
%   Psychtoolbox times (GetSecs); they are put on the NIP clock with the line
%   nipClock fits to the trial's NIP read pairs. NIP times (eye samples,
%   analog cursors) need no conversion. documentation/timing.md has the
%   details.
%
%   Filled here
%     start_tick, stop_ms
%     state.<name>    count; one row per entry: requested_ms (when setstate
%                     ran) and displayed_ms, photon_ms, delay_ms (NaN until
%                     GraphicsHandler fills them); code (its Trellis marker)
%     targets.<name>  the target's settings; computed (every position getpos
%                     worked out: time_ms, x_deg, y_deg); events, frames
%     tags.<name>     events, frames of each mh.Screen(..., 'Tag', name) item
%     data.time_ms, data.cursor(k).time_ms
%     data.stimulus_events.requested_ms and entry (for state rows: which
%                     entry into the state the row shows)
%     data.clock_sync.fit, start_secs, trial_start_tick, trial_start_sample
%   events and frames are slices of data.stimulus_events / stimulus_frames
%   (objectTiming); until GraphicsHandler saves its flip log they hold only
%   what the task asked for.
if nargin < 2, screenparams = []; end
TPM = 30;                                           % NIP ticks per ms
warnState = warning('off', 'MATLAB:structOnObject');
restore = onCleanup(@() warning(warnState));

if isobject(tr), s = struct(tr); else, s = tr; end
if isRecord(s), return, end
for f = {'start_tick', 'start_clock', 'stop_ms', 'tags'}
    if ~isfield(s, f{1}), s.(f{1}) = []; end
end
if ~isstruct(s.state), s.state = struct(); end

D = s.data;
if isobject(D), D = struct(D); end
hasData = isstruct(D) && isfield(D, 'clock_sync') && isstruct(D.clock_sync);
if hasData, C = D.clock_sync; else, C = struct(); end

% ---- the timeline: t = 0 at start_autogenerated
[toTick, C.fit] = nipClock(getf(C, 'nip_pairs', zeros(0, 2)));
startSecs = NaN;
if isfield(s.state, 'start_autogenerated') && ~isempty(s.state.start_autogenerated.time)
    startSecs = s.state.start_autogenerated.time(1);
end
start = toTick(startSecs);                          % not rounded: the start is exactly 0 ms
if ~isfinite(start), start = double(getf(s, 'start_tick', NaN)); end   % starttrial's estimate
s.start_tick = start;
if isfinite(C.fit.ticks_per_s)
    ms = @(t) (toTick(t) - start) / TPM;            % GetSecs -> ms since the start
else
    % no NIP reads this trial: GetSecs times stay relative to the start, but
    % are not on the NIP clock
    ms = @(t) (t - startSecs) * 1000;
    C.fit.note = 'no NIP read pairs: GetSecs times are relative to the start, not on the NIP clock';
end
tickMs = @(k) (double(k) - start) / TPM;            % NIP tick -> ms since the start
C.start_secs = startSecs;
C.trial_start_tick = start;
s.stop_ms = ms(getf(C, 'stop_secs', NaN));

% ---- eye / photodiode samples, cursors
if hasData
    n = max(size(getf(D, 'eyepos', []), 2), numel(getf(D, 'photodiode', [])));
    D.time_ms = tickMs(getf(C, 'trace_start_tick', NaN) + TPM * (0:n-1));
    C.trial_start_sample = NaN;
    if n > 0 && all(isfinite(D.time_ms([1 end])))
        [~, C.trial_start_sample] = min(abs(D.time_ms));   % the sample at t = 0
    end
    if isfield(D, 'timestamps'), D = rmfield(D, 'timestamps'); end
    cur = struct('id', {}, 'pos', {}, 'time_ms', {});
    c0 = getf(D, 'cursor', []);
    for k = 1:numel(c0)
        c = c0(k);
        t = nan(1, size(c.pos, 1));
        if isfield(c, 'secs') && numel(c.secs) == numel(t), t = ms(c.secs(:)'); end
        if isfield(c, 'tick') && numel(c.tick) == numel(t)
            a = isfinite(c.tick);                   % analog cursor: when the NIP sampled it
            t(a) = tickMs(c.tick(a));
        end
        cur(end+1) = struct('id', c.id, 'pos', c.pos, 'time_ms', t); %#ok<AGROW>
    end
    D.cursor = cur;
end

% ---- states: one row per entry
sc = getf(D, 'stateCodes', []);
names = fieldnames(s.state);
chT = zeros(0, 1); chName = cell(0, 1); chK = zeros(0, 1);   % every setstate call, in time order
for i = 1:numel(names)
    st = s.state.(names{i});
    t = getf(st, 'time', []); t = t(:);
    code = NaN;
    if isstruct(sc) && isfield(sc, 'name')
        j = find(strcmp(sc.name, names{i}), 1);
        if ~isempty(j), code = double(sc.code(j)); end
    end
    z = nan(numel(t), 1);
    s.state.(names{i}) = struct('count', getf(st, 'count', numel(t)), 'requested_ms', ms(t), ...
        'displayed_ms', z, 'photon_ms', z, 'delay_ms', z, 'code', code);
    chT = [chT; t]; chName = [chName; repmat(names(i), numel(t), 1)]; chK = [chK; (1:numel(t))']; %#ok<AGROW>
end
[chT, o] = sort(chT); chName = chName(o); chK = chK(o);
change = [true(min(1, numel(chT)), 1); ~strcmp(chName(2:end), chName(1:end-1))];   % a repeat of the current state is not a change
chT = chT(change); chName = chName(change); chK = chK(change);   % calls that changed the state

% ---- stimulus_events: requested_ms. A state row is the state change it
% shows: its time is when setstate ran (as in trial.state), not when the
% first frame of the new state was published.
if hasData && isstruct(getf(D, 'stimulus_events', [])) && isfield(D.stimulus_events, 'request_secs')
    E = D.stimulus_events;
    g = E.request_secs(:);
    E.requested_ms = ms(g);
    E.entry = nan(numel(g), 1);
    for j = find(strcmp(E.event, 'state'))'
        c = find(chT <= g(j), 1, 'last');
        if ~isempty(c) && strcmp(chName{c}, E.state{j})
            E.requested_ms(j) = ms(chT(c));
            E.entry(j) = chK(c);
        end
    end
    D.stimulus_events = rmfield(E, 'request_secs');
end

% ---- targets: settings, and every position getpos worked out
if isstruct(s.targets)
    tn = fieldnames(s.targets);
    for i = 1:numel(tn)
        T = s.targets.(tn{i});
        if isobject(T), T = struct(T); end
        if ~isstruct(T), continue, end
        comp = computedPositions(T, ms, screenparams);
        T = rmfield(T, intersect(fieldnames(T), {'timestamp', 'moving_position'}));
        T.events = []; T.frames = [];
        T.computed = comp;
        s.targets.(tn{i}) = T;
    end
end
if ~isstruct(s.tags), s.tags = struct(); end

if hasData
    D.clock_sync = C;
    s.data = D;
end
s = objectTiming(s);
end

% =========================================================================
function c = computedPositions(T, ms, screenparams)
% One row per getpos call: when (time_ms) and where (degrees, the display's
% centre at 0, +y up) it put the target. A target that does not move keeps
% one position and no times.
pos = double(getf(T, 'moving_position', zeros(0, 2)));
ts = getf(T, 'timestamp', []);
n = size(pos, 1);
c = struct('time_ms', nan(n, 1), 'x_deg', nan(n, 1), 'y_deg', nan(n, 1));
if n == 0 || size(pos, 2) < 2, return, end
if numel(ts) == n, c.time_ms = ms(ts(:)); end
% the units getpos used for these positions
type = lower(char(getf(T, 'degreestype', 'cart')));
if isempty(getf(T, 'custompath_x', [])) && any(strcmp(type, {'pol', 'polar'})), type = 'cart'; end
switch type
    case {'cart', 'cartesian'}
        c.x_deg = pos(:, 1); c.y_deg = pos(:, 2);
    case {'pol', 'polar'}
        [c.x_deg, c.y_deg] = pol2cart(deg2rad(pos(:, 1)), pos(:, 2));
    case 'mm'
        try
            deg = pix2deg(deg2pix(pos, 'mm', screenparams), 'cart', screenparams);
            if size(deg, 1) == n, c.x_deg = deg(:, 1); c.y_deg = deg(:, 2); end
        catch
        end
end
end

function tf = isRecord(s)
% already in the saved form: the states carry requested_ms
tf = false;
if ~isfield(s, 'state') || ~isstruct(s.state), return, end
f = fieldnames(s.state);
tf = ~isempty(f) && isfield(s.state.(f{1}), 'requested_ms');
end

function v = getf(s, f, default)
if isstruct(s) && isfield(s, f) && ~isempty(s.(f)), v = s.(f); else, v = default; end
end
