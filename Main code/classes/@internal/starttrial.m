function starttrial(mh)
stimDestination();   % cache the stim address before the trial loop needs it: the first read takes 7-90 ms
mh.trialstarted = 1;
% fresh stimulus-timing logs for this trial (see buildStimulusTiming)
mh.stimReqN = 0;
frameItems('reset');                  % nothing on screen yet, no state
mh.stimFirstSeq = mh.sceneSeq + 1;   % the first frame this trial publishes
nipTick('reset');                     % fresh Psychtoolbox <-> NIP clock pairs
% The trial start is t = 0 of every saved *_ms time. These are first
% estimates; trialRecord replaces start_tick with start_autogenerated's
% GetSecs on the fitted NIP clock when the trial is saved.
mh.trial.start_tick = nipTick;        % NIP tick now
mh.trial.start_clock = datetime('now');
mh.setstate('start_autogenerated')

mh.autocalibrationmatrix_buffer = mh.autocalibrationmatrix;
xippmex('digout', 4, 1)
justonce=0;
for i=1:50
    mh.Screen('FillOval', 'windowPtr', [0 0 0],[8000 8000 8050 8050]);
    justonce=justonce+1;
    % mh.evalgraphics(['gr.activestatename =' '''' mh.activestatename '''' ';gr.flipped=0;'])
    % writeline(mh.graphicsport,'trialstart','0.0.0.0',2023);
    mh.Screen('sendtogr')
    if justonce==1
    mh.makesound('sine',850,1,0.3);
    end
    pause(0.001)
end

xippmex('digout', 4, 0);
% [~,~,events]=xippmex('digin');
mh.stimmed=0;
end