function ev = stimulusRequests(mh)
%STIMULUSREQUESTS This trial's change log, as the start of data.stimulus_events.
%   One row per item appearing or disappearing on the display and per state
%   change, with the ID (request_frame) and Psychtoolbox time (requested) of
%   the first frame that asked for it, as publishFrame logged them.
%   GraphicsHandler fills in the displayed columns when it saves its flip log
%   (buildStimulusTiming); until then they are NaN.
n = mh.stimReqN;
z = nan(n, 1);
ev = struct( ...
    'tag',             {col(mh.stimReqTag(1:n))}, ...
    'kind',            {col(mh.stimReqKind(1:n))}, ...
    'event',           {col(mh.stimReqEvent(1:n))}, ...
    'state',           {col(mh.stimReqState(1:n))}, ...
    'requested',       col(mh.stimReqTime(1:n)), ...
    'request_frame',   col(mh.stimReqSeq(1:n)), ...
    'displayed',       z, ...
    'delay',           z, ...
    'flip',            z, ...
    'frame_id',        z, ...
    'onset_tick',      z, ...
    'photon_tick',     z, ...
    'x_deg',           z, ...
    'y_deg',           z, ...
    'rect_px',         nan(n, 4), ...
    'missed',          false(n, 1));
end

function v = col(v)
v = reshape(v, [], 1);
end
